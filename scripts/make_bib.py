"""Build references.bib from the "## מקורות לפרק" lists in chapters/*.txt (the TXT files stay
the source of truth). Keys are the source IDs (S-chXX-NN), so [S-chXX-NN] in the text maps to
\\cite{S-chXX-NN}. Output: references.bib (IEEE style is applied by biblatex at compile time).
Run from the project root:  python scripts/make_bib.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LINE = re.compile(r"^- \[(S-ch\d\d-\d\d)\] (.*)$")
YEAR = re.compile(r"^(?P<auth>.*?)\s\((?P<year>n\.d\.|\d{4}[a-z]?)(?P<extra>[^)]*)\)\.\s(?P<rest>.*)$")
URL = re.compile(r"https?://[^\s)]+")


def split_title(rest):
    # The title ends at the first ". " that does not close a section number such as "3.4."
    # or an initial such as "J."
    for m in re.finditer(r"([^\s]*)\.\s", rest):
        tok = m.group(1)
        if re.fullmatch(r"[\d.]+", tok) or re.fullmatch(r"[A-Z]", tok):
            continue
        return rest[: m.end(1)].strip(), rest[m.end():].strip()
    return rest.strip().rstrip("."), ""


def bib_authors(a):
    a = a.strip()
    if not re.search(r"\b[A-Z]\.", a):                 # corporate author
        return "{" + a.rstrip(".").strip() + "}"
    a = re.sub(r",?\s*et al\.?$", ", others", a)
    a = re.sub(r",?\s*&\s*", ", ", a)
    parts = [p.strip() for p in a.split(",") if p.strip()]
    names, i = [], 0
    while i < len(parts):
        if parts[i] == "others":
            names.append("others"); i += 1; continue
        last = parts[i]; first = parts[i + 1] if i + 1 < len(parts) else ""
        names.append(f"{last}, {first}".strip(", ")); i += 2
    return " and ".join(names)


def esc(s):
    return (s.replace("\\", "").replace("&", r"\&").replace("%", r"\%")
             .replace("#", r"\#").replace("_", r"\_"))


def entry(key, text):
    m = re.search(r"\s*\(([^()]*[֐-׿][^()]*)\)\s*$", text)   # Hebrew remark at the end
    if m:
        text = text[: m.start()]
    urls = URL.findall(text)
    text_wo = re.sub(r"\(PDF:\s*\)", "", URL.sub("", text)).strip().rstrip(".").strip()
    fields = {}
    y = YEAR.match(text_wo)
    if y:
        fields["author"] = bib_authors(y["auth"])
        if y["year"] == "n.d.":
            fields["note"] = "n.d."
        else:
            fields["year"] = y["year"]
        if y["extra"].strip(", "):
            fields["note"] = y["extra"].strip(", ")
        title, venue = split_title(y["rest"])
    else:
        title, venue = split_title(text_wo)
    fields["title"] = "{" + esc(title) + "}"
    if venue:
        fields["howpublished"] = esc(venue.rstrip(". "))
    doi = [u.rstrip(".") for u in urls if "doi.org/" in u]
    if doi:
        fields["doi"] = doi[0].split("doi.org/")[1]
    other = [u.rstrip(".") for u in urls if "doi.org/" not in u]
    if other:
        fields["url"] = other[-1]          # a trailing "(PDF: ...)" link is the full text
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v)
    return f"@misc{{{key},\n{body}\n}}\n"


def collect():
    refs = {}
    for f in sorted((ROOT / "chapters").glob("chapter_*.txt")):
        t = f.read_text(encoding="utf-8")
        for line in t.partition("## מקורות לפרק")[2].splitlines():
            m = LINE.match(line.strip())
            if m:
                refs.setdefault(m[1], m[2])
    return refs


def main():
    refs = collect()
    out = "% Generated by scripts/make_bib.py from chapters/*.txt. Do not edit by hand.\n\n"
    out += "\n".join(entry(k, v) for k, v in sorted(refs.items()))
    (ROOT / "references.bib").write_text(out, encoding="utf-8")
    print(f"references.bib: {len(refs)} entries")


if __name__ == "__main__":
    main()
