"""Convert chapters/*.txt (source of truth) to latex/chapters/*.tex for the aibook class.

Markup (docs/STYLE_GUIDE.md section 5) -> LaTeX:
  line 1 "פרק N — כותרת" / "נספח — כותרת"   -> \\chapter ; first sentence after it -> \\chapterquestion
  "## כותרת"                               -> \\section ; "## תובנות מרכזיות" -> insightsbox
  "## מקורות לפרק/לנספח"                   -> end of chapter (global IEEE bibliography instead)
  five box markers                         -> behindbox / thinkbox / labbox / conceptbox / mythbox
  [נוסחה] ... [/נוסחה]                     -> equation
  $...$ inside a line                      -> inline math, raw LaTeX (a literal dollar sign is not allowed)
  [טבלה X: t] rows "a | b" [/טבלה]          -> table + tabularx (first row = header)
  [איור X: t | ...]                        -> figure (asset from FIGURES below)
  [ממתין ...]                              -> \\placeholder (qa-typeset fails the build on it)
  [S-chXX-NN] ([S-..])                     -> \\cite{...};  "איור 5.1" / "טבלה 5.1" in prose -> \\ref
Run from the project root:  python scripts/txt2tex.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "latex" / "chapters"

# Figure id -> (kind, path relative to project root). Every figure is generated by code.
FIGURES = {
    "1.1": ("tikz", "latex/figures/fig1_1.tex"),
    "2.1": ("tikz", "latex/figures/fig2_1.tex"),
    "3.1": ("pdf", "assets/charts/fig3_1_activations.pdf"),
    "3.2": ("tikz", "latex/figures/fig3_2.tex"),
    "4.1": ("pdf", "assets/charts/fig4_1_temperature.pdf"),
    "4.2": ("tikz", "latex/figures/fig4_2.tex"),
    "5.1": ("pdf", "assets/charts/fig5_1_accuracy.pdf"),
    "6.1": ("tikz", "latex/figures/fig6_1.tex"),
    "7.1": ("tikz", "latex/figures/fig7_1.tex"),
    "נ.1": ("tikz", "latex/figures/figA_1.tex"),
    "נ.2": ("pdf", "assets/charts/figA_2_scores.pdf"),
}
BOXES = {
    "מאחורי הקלעים": ("behindbox", True),
    "רגע של מחשבה": ("thinkbox", False),
    "במעבדה": ("labbox", True),
    "מושג שכדאי להכיר": ("conceptbox", True),
    "מיתוס מול מציאות": ("mythbox", False),
}
CITE = re.compile(r"\[(S-ch\d\d-\d\d)\](?:\s*\[(S-ch\d\d-\d\d)\])*")
CITE_ALL = re.compile(r"S-ch\d\d-\d\d")
warnings = []


def esc(s):
    s = s.replace("\u200f", "").replace("\u200e", "")          # bidi marks: LuaTeX does not need them
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"), ("$", r"\$"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    s = s.replace(r"\textbackslash\{\}", r"\textbackslash{}")
    # Characters missing from the Assistant font are typeset as math (qa-typeset: no "Missing character")
    sub = str.maketrans("₀₁₂₃₄₅₆₇₈₉", "0123456789")
    s = re.sub(r"([A-Za-z])([₀-₉]+)", lambda m: f"${m[1]}_{{{m[2].translate(sub)}}}$", s)
    for ch, tex in (("σ", r"$\sigma$"), ("←", r"$\leftarrow$"), ("→", r"$\rightarrow$"),
                    ("≈", r"$\approx$"), ("×", r"$\times$"), ("−", "-"), ("…", "...")):
        s = s.replace(ch, tex)
    return s


def label_id(x):
    return x.replace("נ", "A")


MATH = re.compile(r"\$([^$\n]+)\$")


def inline(s):
    # Inline math "$...$" is passed to LaTeX unescaped (M5B: raw "x_i" / "\sum" leaked into the
    # PDF as text, page 17 of v0.9). Math is protected by placeholders while the rest is escaped.
    maths = []
    def _keep(m):
        maths.append("$" + m[1] + "$")
        return f"\x00{len(maths) - 1}\x00"
    s = MATH.sub(_keep, s)
    s = esc(s)
    s = CITE.sub(lambda m: r"\cite{" + ",".join(CITE_ALL.findall(m.group(0))) + "}", s)
    # project-document references used by the appendix, e.g. [docs/PROMPT_HISTORY.md, רשומה 002]
    # paths go into \nolinkurl so that long paths can break at "/" (overfull box, IR-13)
    def _projref(m):
        parts = m.group(1).split(",", 1)
        path = parts[0].strip().replace(r"\_", "_")
        rest = ("," + parts[1]) if len(parts) > 1 else ""
        return r"\projref{\nolinkurl{" + path + "}" + rest + "}"
    s = re.sub(r"\[((?:docs|agents|chapters|python|prompts)/[^\]]+)\]", _projref, s)
    s = re.sub(r"(איור|טבלה)\s+(\d|נ)\.(\d+)",
               lambda m: f"{m[1]}~\\ref{{{'fig' if m[1] == 'איור' else 'tab'}:{label_id(m[2])}.{m[3]}}}", s)
    s = re.sub(r"(\s)-\s", r"\1--\\ ", s)
    if "[" in s and re.search(r"\[[^\]]*\]", s):
        warnings.append(f"unconverted bracket markup: {s[:80]}")
    s = re.sub(r"\x00(\d+)\x00", lambda m: maths[int(m[1])], s)
    return s


def fig_block(line):
    m = re.match(r"\[איור\s+([\dנ]+\.\d+):\s*([^|]+)\|(.*)\]\s*$", line)
    if not m:
        warnings.append(f"bad figure line: {line[:80]}"); return ""
    fid, title, rest = m[1], m[2].strip(), m[3]
    fields = {k.strip(): v.strip() for k, _, v in (p.partition(":") for p in rest.split("|"))}
    kind, path = FIGURES.get(fid, (None, None))
    if not kind or not (ROOT / path).exists():
        warnings.append(f"missing asset for figure {fid}")
        body = r"\placeholder{איור " + fid + " חסר}"
    elif kind == "pdf":
        body = r"\includegraphics[width=\linewidth]{" + path + "}"
    else:
        body = r"\input{" + path + "}"
    notes = []
    cap = re.search(r'כיתוב:\s*"([^"]+)"', fields.get("תוכן", ""))
    if cap:
        notes.append(inline(cap.group(1)))
    src = fields.get("מקור הנתונים", "")
    if src:
        src_tex = inline(src)
        src_tex = re.sub(r"(?<![{,])\b(S-ch\d\d-\d\d)\b", r"\\cite{\1}", src_tex)
        notes.append("מקור: " + src_tex)
    note = (r"\figurenote{" + " · ".join(notes) + "}") if notes else ""
    return ("\\begin{figure}[htbp]\n\\centering\n" + body + "\n\\caption{" + inline(title) + "}"
            f"\\label{{fig:{label_id(fid)}}}\n" + note + "\n\\end{figure}\n")


def table_block(head, rows):
    m = re.match(r"\[טבלה\s+(\d+\.\d+):\s*(.+)\]\s*$", head)
    tid, title = m[1], m[2]
    cells = [[c.strip() for c in r.split("|")] for r in rows if r.strip()]
    ncol = max(len(r) for r in cells)
    numeric = all(re.fullmatch(r"[\d.,%\s]+", c) for r in cells[1:] for c in r) if len(cells) > 1 else False
    spec = ("c" * ncol) if numeric else ("R" * ncol)
    env = "tabular" if numeric else "tabularx"
    width = "" if numeric else r"{\linewidth}"
    out = ["\\begin{table}[htbp]", "\\centering", f"\\caption{{{inline(title)}}}\\label{{tab:{tid}}}",
           "\\begingroup\\small\\renewcommand{\\arraystretch}{1.35}\\booktablerule",
           f"\\begin{{{env}}}{width}{{{spec}}}", "\\toprule"]
    for i, r in enumerate(cells):
        r = r + [""] * (ncol - len(r))
        if any(c.startswith("[ממתין") for c in r):
            out.append(f"\\multicolumn{{{ncol}}}{{c}}{{\\textcolor{{red!70!black}}{{סימון מקום: {inline(' '.join(r).strip('[]'))}}}}}\\\\")
            warnings.append(f"placeholder inside table {tid}")
            continue
        if i == 0:
            out.append("\\rowcolor{midnight}" + " & ".join(f"\\tabhead{{{inline(c)}}}" for c in r) + "\\\\ \\midrule")
        else:
            out.append(" & ".join(inline(c) for c in r) + ("\\\\ \\midrule" if False else "\\\\"))
    out += ["\\bottomrule", f"\\end{{{env}}}", "\\endgroup", "\\end{table}", ""]
    return "\n".join(out)


def convert(lines, kind):
    out, para, i = [], [], 0
    in_list = None
    box_stack = []

    def flush():
        nonlocal para
        if para:
            out.append(inline(" ".join(para)) + "\n")
            para = []

    def close_list():
        nonlocal in_list
        if in_list:
            out.append(f"\\end{{{in_list}}}\n"); in_list = None

    title_line = lines[0].strip()
    t = re.match(r"(?:פרק\s+\d+|נספח)\s+—\s+(.+)", title_line)
    chapter_title = t[1] if t else title_line
    i = 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    question = lines[i].strip(); i += 1
    out.append(f"\\chapterlayout{{{kind}}}\n")   # tight layout per chapter (scripts/layout.py, IR-15)
    out.append(f"\\chapterquestion{{{inline(question)}}}\n\\chapter{{{inline(chapter_title)}}}\\label{{ch:{kind}}}\n")
    insights = False
    while i < len(lines):
        raw = lines[i].rstrip("\n"); s = raw.strip(); i += 1
        if s.startswith("## "):
            flush(); close_list()
            if insights:
                out.append("\\end{insightsbox}\n"); insights = False
            h = s[3:].strip()
            if h.startswith("מקורות ל"):
                break
            if h == "תובנות מרכזיות":
                out.append("\\begin{insightsbox}\n"); insights = True
            else:
                out.append(f"\\section{{{inline(h)}}}\n")
            continue
        if not s:
            flush(); close_list(); continue
        m = re.match(r"\[/(מאחורי הקלעים|רגע של מחשבה|במעבדה|מושג שכדאי להכיר|מיתוס מול מציאות)\]$", s)
        if m:
            flush(); close_list()
            out.append(f"\\end{{{BOXES[m[1]][0]}}}\n"); box_stack.pop(); continue
        m = re.match(r"\[(מאחורי הקלעים|רגע של מחשבה|במעבדה|מושג שכדאי להכיר|מיתוס מול מציאות)(?::\s*(.+))?\]$", s)
        if m:
            flush(); close_list()
            env, has_title = BOXES[m[1]]
            out.append(f"\\begin{{{env}}}" + (f"{{{inline(m[2] or '')}}}" if has_title else "") + "\n")
            box_stack.append(env); continue
        if box_stack and box_stack[-1] == "mythbox" and (s.startswith("מיתוס:") or s.startswith("מציאות:")):
            flush()
            if s.startswith("מיתוס:"):
                out.append("\\mythlabel " + inline(s[len("מיתוס:"):].strip()) + "\n")
            else:
                out.append("\\tcblower\n\\realitylabel " + inline(s[len("מציאות:"):].strip()) + "\n")
            continue
        m = re.match(r"\[נוסחה\]\s*(.+?)\s*\[/נוסחה\]$", s)
        if m:
            flush(); close_list()
            out.append("\\begin{equation}\n" + m[1] + "\n\\end{equation}\n"); continue
        if s.startswith("[טבלה "):
            flush(); close_list()
            rows = []
            while i < len(lines) and lines[i].strip() != "[/טבלה]":
                rows.append(lines[i].strip()); i += 1
            i += 1
            out.append(table_block(s, rows)); continue
        if s.startswith("[איור "):
            flush(); close_list(); out.append(fig_block(s)); continue
        if s.startswith("[ממתין"):
            flush(); close_list()
            warnings.append(f"placeholder: {s[:70]}")
            out.append("\\placeholder{" + inline(s.strip("[]")) + "}\n"); continue
        lm = re.match(r"^(-|\d+\.)\s+(.*)$", s)
        if lm:
            flush()
            want = "itemize" if lm[1] == "-" else "enumerate"
            if in_list != want:
                close_list(); out.append(f"\\begin{{{want}}}\n"); in_list = want
            out.append("\\item " + inline(lm[2]) + "\n"); continue
        close_list()
        para.append(s)
        if box_stack:            # inside a box every TXT line is its own paragraph
            flush()
    flush(); close_list()
    if insights:
        out.append("\\end{insightsbox}\n")
    if box_stack:
        warnings.append(f"unclosed boxes: {box_stack}")
    return "".join(out)


def convert_abstract(path):
    text = path.read_text(encoding="utf-8").splitlines()
    body, keywords = [], ""
    for line in text[1:]:
        s = line.strip()
        if s.startswith("מילות מפתח:"):
            keywords = s.split(":", 1)[1].strip()
        else:
            body.append(s)
    paras = "\n".join(body).strip().split("\n\n")
    tex = "\n\n".join(inline(" ".join(p.split("\n"))) for p in paras if p.strip())
    return tex, keywords


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    header = "% Generated by scripts/txt2tex.py from chapters/{name}.txt. Edit the TXT, not this file.\n"
    for f in sorted((ROOT / "chapters").glob("*.txt")):
        if f.stem == "abstract":
            tex, kw = convert_abstract(f)
            fm = ROOT / "latex" / "frontmatter"; fm.mkdir(parents=True, exist_ok=True)
            (fm / "abstract.tex").write_text(header.format(name=f.stem) + tex + "\n", encoding="utf-8")
            (fm / "keywords.tex").write_text(header.format(name=f.stem) + inline(kw) + "\n", encoding="utf-8")
            continue
        kind = f.stem.replace("chapter_", "")
        tex = convert(f.read_text(encoding="utf-8").splitlines(), kind)
        (OUT / f"{f.stem}.tex").write_text(header.format(name=f.stem) + tex, encoding="utf-8")
    for w in warnings:
        print("WARNING:", w)
    print(f"txt2tex: done, {len(warnings)} warnings")
    return 1 if any(w.startswith(("bad", "missing", "unclosed")) for w in warnings) else 0


if __name__ == "__main__":
    sys.exit(main())
