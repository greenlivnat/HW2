"""Systematic fix for near-empty chapter-end pages (M5B, IR-15).

After a LaTeX run, find chapters whose last page holds only a few lines (usually the insights box,
which is unbreakable, IR-09) and list them in latex/layout_tight.tex. The class typesets listed
chapters tighter (\\chapterlayout: smaller paragraph skip, line spread and insights font). A chapter
that is still sparse at level 1 moves to level 2. Lists only grow, so the loop converges; build.py
runs it at most three times. The generated file is tracked in git, so a plain `latexmk main.tex`
gives the same book.

  python scripts/layout.py          # prints the sparse pages; exit 1 if the lists changed
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PDF = ROOT / "main.pdf"
TOC = ROOT / "main.toc"
OUT = ROOT / "latex" / "layout_tight.tex"
MIN_LINES = 14          # a full text page has about 40 non-empty lines in pdftotext -layout


def chapter_ranges():
    toc = TOC.read_text(encoding="utf-8", errors="replace")
    starts = re.findall(r"\\contentsline \{chapter\}\{(?:\\numberline \{([^}]*)\})?[^\n]*?\}\{(\d+)\}\{", toc)
    units = []
    for (num, page), (_, nxt) in zip(starts, starts[1:]):
        if num.isdigit():
            units.append((f"{int(num):02d}", int(page), int(nxt) - 1))
        elif num == "נ":
            units.append(("appendix", int(page), int(nxt) - 1))
    return units


def lines_on(page):
    t = subprocess.run(["pdftotext", "-enc", "UTF-8", "-layout", "-f", str(page), "-l", str(page), str(PDF), "-"],
                       capture_output=True, text=True, encoding="utf-8", timeout=60).stdout
    return sum(1 for l in t.splitlines() if l.strip())


def current(cmd):
    if not OUT.exists():
        return set()
    m = re.search(r"\\" + cmd + r"\{([^}]*)\}", OUT.read_text(encoding="utf-8"))
    return {x for x in (m.group(1).split(",") if m else []) if x}


def main():
    tight, tighter = current("tightchapters"), current("tighterchapters")
    sparse = []
    for unit, first, last in chapter_ranges():
        if last > first and lines_on(last) < MIN_LINES:
            sparse.append(unit)
            print(f"sparse chapter end: {unit}, page {last}")
    new_tight = tight | set(sparse)
    new_tighter = tighter | {u for u in sparse if u in tight}
    if (new_tight, new_tighter) != (tight, tighter):
        OUT.write_text("% Generated by scripts/layout.py: chapters typeset tighter to avoid near-empty end pages.\n"
                       f"\\tightchapters{{{','.join(sorted(new_tight))}}}\n"
                       f"\\tighterchapters{{{','.join(sorted(new_tighter))}}}\n", encoding="utf-8")
        print("layout_tight.tex updated:", sorted(new_tight), "level 2:", sorted(new_tighter))
        sys.exit(1)
    print("layout stable:", sorted(tight), "level 2:", sorted(tighter))


if __name__ == "__main__":
    main()
